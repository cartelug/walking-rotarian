// Assembles the final ChatGPT prompt for each planned picture from docs/candid-prompt-pack.json.
//
// Run:  node tools/assemble-prompts.mjs                writes docs/prompts-ready.md (every shot, in running order)
//       node tools/assemble-prompts.mjs road-bootlace  prints one shot
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pack = JSON.parse(fs.readFileSync(path.join(ROOT, "docs", "candid-prompt-pack.json"), "utf8"));

// ChatGPT makes square, 3:2 and 2:3 pictures. Other shapes are cropped by tools/make_scenes.py.
const SIZE = { "3:2": "1536 x 1024 (landscape)", "16:9": "1536 x 1024 (landscape); cropped to 16:9 afterwards", "2:3": "1024 x 1536 (portrait)", "4:5": "1024 x 1536 (portrait); cropped to 4:5 afterwards" };

export function assemble(s) {
  const person = s.kind === "person";
  return person
    ? `${pack.identityBlock} Scene: ${s.scene} ${pack.styleBlock} ${pack.negativeBlock} Aspect ratio ${s.aspect}.`
    : `${pack.styleBlockNoPerson} Scene: ${s.scene} ${pack.negativeBlock} Aspect ratio ${s.aspect}.`;
}

const attach = (s) => (s.kind === "person" ? s.inputs.map((k) => { const [file, role] = pack.inputRoles[k].split(". "); return `**${k}**: ${file}. ${role || ""}`.trim(); }).join("<br>") : "none");
const block = (s) => `### ${s.id}${s.pilot ? " (pilot)" : ""}

- **Shape:** ${s.aspect}. Ask ChatGPT for ${SIZE[s.aspect]}.
- **Attach:** ${attach(s)}
- **Save as:** \`${s.id}.png\`
- **Label that will be shown:** ${s.caption}${s.poseBasis ? `\n- **Pose basis:** ${s.poseBasis}. Drift risk: ${s.driftRisk}.` : ""}

\`\`\`text
${assemble(s)}
\`\`\`

**Short form** (use this if you saved the master prompt, see above):

\`\`\`text
Scene: ${s.scene} Aspect ratio ${s.aspect}.
\`\`\`
`;

const arg = process.argv[2];
if (arg) {
  const s = pack.shots.find((x) => x.id === arg);
  if (!s) { console.error("No such shot: " + arg); process.exit(2); }
  console.log(assemble(s));
} else {
  const order = [["Pilot: run these six first", (s) => s.pilot], ["Wave 1: scenery and objects (no person, no identity risk)", (s) => s.wave === 1], ["Wave 2: the remaining remakes (four of the six are already in the pilot)", (s) => s.wave === 2 && !s.pilot], ["Wave 3: more candid scenes, only for gaps that real photographs leave", (s) => s.wave === 3 && !s.pilot]];
  const out = [`# Prompts ready for ChatGPT Images

Generated by \`node tools/assemble-prompts.mjs\` from \`docs/candid-prompt-pack.json\`. Edit the pack, not this file.

**The rules for running these are in \`docs/GENERATION-PROTOCOL.md\`** (before-you-start checks, the pilot decision, the review gate, the three-attempt limit and the log). Read it first.

## How to run each one

1. Start a **new chat** for every picture, so one result does not steer the next.
2. For a person shot, attach the listed reference photographs from the Drive folder **Shyaka Mbanda - Authoritative References - 2026-10-28**. Always attach the portrait. Never attach an earlier generated picture as the only reference.
3. Paste the prompt. Ask for the size shown.
4. Check the result with the review gate below. If it fails, run it again from the original photographs, not from the failed result.
5. Save the file with the name shown, in one folder.
6. Then, in the repository: \`node tools/ingest-drive.mjs <folder> --write\`, then \`python3 -I tools/make_scenes.py\`, then \`node tools/check_images.mjs\`.
7. A person picture stays blocked until its row in \`src/data/image-register.json\` has \`generation.gate\` set to \`passed\` and \`branding.removed\` set to \`true\`. The Reviewer must have passed it first (see the protocol).

## Review gate

${pack.reviewGate.map((x) => "- " + x).join("\n")}

The pilot comes first: ${pack.process[0].replace(/^1\.\s*/, "")} ${pack.process[1].replace(/^2\.\s*/, "")}
`];
  const F = "`".repeat(3), TAIL = "When I give you a scene (and attach photographs), make that one picture using the rules above. Put no text, logos or captions in the picture.";
  out.push([
    "## The master prompts (optional: save once)", "",
    "If your ChatGPT has Projects, save each block below as the instructions of its own Project (for example \"Mbanda: people\" and \"Mbanda: scenery\"). Every new chat in that Project then needs only the attached photographs and the short form of the scene. If it does not, use the full prompt for each picture.", "",
    "### Master prompt: people", "", F + "text", [pack.identityBlock, pack.styleBlock, pack.negativeBlock, TAIL].join(" "), F, "",
    "### Master prompt: scenery and objects", "", F + "text", [pack.styleBlockNoPerson, pack.negativeBlock, TAIL.replace(" (and attach photographs)", "")].join(" "), F, "",
  ].join("\n"));
  const done = new Set();
  for (const [title, f] of order) {
    const list = pack.shots.filter((s) => f(s) && !done.has(s.id));
    list.forEach((s) => done.add(s.id));
    out.push(`## ${title} (${list.length})\n\n${list.map(block).join("\n")}`);
  }
  fs.writeFileSync(path.join(ROOT, "docs", "prompts-ready.md"), out.join("\n"));
  console.log(`Wrote docs/prompts-ready.md (${done.size} prompts).`);
}
